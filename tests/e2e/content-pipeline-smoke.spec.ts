import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("daily content workflow is protected and stage-gated", async () => {
  const workflow = await readFile(".github/workflows/content-acquisition-daily.yml", "utf8");
  const videoHosting = await readFile("scripts/host-video-candidate-to-bunny.ts", "utf8");
  const batchHosting = await readFile("scripts/host-video-candidates-to-bunny.ts", "utf8");
  expect(workflow).toContain("concurrency:");
  expect(workflow).toContain("workflow_dispatch:");
  expect(workflow).toContain("article_mode:");
  expect(workflow).toContain("media_mode:");
  expect(workflow).toContain('default: "auto-publish"');
  expect(workflow).toContain("discover-only");
  expect(workflow).toContain("review-only");
  expect(workflow).toContain("auto-publish");
  expect(workflow).toContain("content:pipeline");
  expect(workflow).toContain("media-daily");
  expect(workflow).toContain("continue-on-error: true");
  expect(workflow).toContain("timeout-minutes: 60");
  expect(workflow).toContain('tee "$RUNNER_TEMP/article-daily.log"');
  expect(workflow).toContain('published=${counts.published ?? 0}');
  expect(workflow).toContain("Fail after independent stage attempts");
  expect(workflow).toContain("MINIMAX_API_KEY");
  expect(workflow).toContain("YOUTUBE_DATA_API_KEY");
  expect(workflow).toContain("YOUTUBE_COOKIES_B64: ${{ secrets.YOUTUBE_COOKIES_B64 }}");
  expect(workflow).toContain("CONTENT_ARTICLE_PUBLICATION_POLICY_VERSION: ${{ vars.CONTENT_ARTICLE_PUBLICATION_POLICY_VERSION || 'readlang-links-v6' }}");
  expect(workflow).toContain("CONTENT_ARTICLE_REVIEW_CONCURRENCY: ${{ vars.CONTENT_ARTICLE_REVIEW_CONCURRENCY || '2' }}");
  expect(workflow).toContain("ARTICLE_MODE: ${{ inputs.article_mode || vars.CONTENT_ARTICLE_DAILY_MODE || 'auto-publish' }}");
  expect(workflow).toContain("MEDIA_MODE: ${{ inputs.media_mode || vars.CONTENT_MEDIA_DAILY_MODE || 'auto-publish' }}");
  expect(workflow).toContain("CONTENT_MEDIA_REVIEW_CONCURRENCY: ${{ vars.CONTENT_MEDIA_REVIEW_CONCURRENCY || '2' }}");
  expect(workflow).toContain("pnpm content:pipeline -- media-daily --mode auto-publish");
  expect(workflow).toContain('--video-daily-limit "$MEDIA_VIDEO_DAILY_LIMIT"');
  expect(workflow).toContain('--podcast-daily-limit "$MEDIA_PODCAST_DAILY_LIMIT"');
  expect(workflow).toContain("--require-bilingual-subtitles");
  expect(workflow).toContain("CONTENT_MEDIA_STT_PROVIDER: ${{ vars.CONTENT_MEDIA_STT_PROVIDER || 'minimax' }}");
  expect(workflow).toContain("pnpm exec tsx scripts/host-video-candidates-to-bunny.ts");
  expect(workflow).toContain("CONTENT_MEDIA_RUNNER_LABELS");
  expect(workflow).toContain("MEDIA_VIDEO_AUTHORIZED_ASSET_DIR");
  expect(workflow).toContain("bgutil-ytdlp-pot-provider==2.0.0");
  expect(workflow).toContain("brainicism/bgutil-ytdlp-pot-provider:2.0.0");
  expect(workflow).toContain("BGUTIL_PROVIDER_CONTAINER: bgutil-ytdlp-pot-provider-${{ github.run_id }}");
  expect(workflow).toContain("--publish 127.0.0.1:4416:4416");
  expect(workflow).toContain("name: Stop PO Token provider");
  expect(workflow).toContain("media_canary_only:");
  expect(workflow).toContain("MEDIA_VIDEO_HOSTING_CANARY_ONLY=true");
  expect(workflow).toContain("publication=skipped");
  expect(videoHosting).toContain('"youtube:player_client=mweb; youtubepot-bgutilhttp:base_url=http://127.0.0.1:4416"');
  expect(batchHosting).toContain("MEDIA_VIDEO_HOSTING_CANARY_ONLY");
  expect(batchHosting).toContain("const canaryCandidateLimit = 10");
  expect(batchHosting).toContain("if (canaryOnly) break");
  expect(workflow).not.toContain('export MEDIA_VIDEO_HOSTING_SINCE=');
  expect(workflow).toContain("(inputs.media_mode || vars.CONTENT_MEDIA_DAILY_MODE || 'auto-publish') == 'auto-publish'");
  expect(workflow).not.toContain("version: 11");
  expect(workflow).not.toContain("content:publish");
});
