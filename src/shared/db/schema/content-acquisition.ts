import { sql } from "drizzle-orm";
import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";

import { createdAt, jsonObject, updatedAt, type JsonObject } from "./common";

export const acquisitionSources = pgTable(
  "acquisition_sources",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    stableKey: text("stable_key").notNull(),
    adapterType: text("adapter_type").notNull(),
    sourceKind: text("source_kind").notNull(),
    externalSourceId: text("external_source_id").notNull(),
    displayName: text("display_name").notNull(),
    language: text("language").notNull(),
    region: text("region"),
    enabled: boolean("enabled").default(false).notNull(),
    rightsStatus: text("rights_status").default("unknown").notNull(),
    rightsPolicy: jsonObject("rights_policy"),
    schedule: jsonObject("schedule"),
    rateLimit: jsonObject("rate_limit"),
    cursor: text("cursor"),
    revision: integer("revision").default(1).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex("acquisition_sources_stable_key_uidx").on(table.stableKey),
    uniqueIndex("acquisition_sources_adapter_external_uidx").on(table.adapterType, table.externalSourceId),
    index("acquisition_sources_enabled_schedule_idx").on(table.enabled, table.updatedAt),
    check("acquisition_sources_revision_positive_check", sql`${table.revision} > 0`),
    check("acquisition_sources_adapter_check", sql`${table.adapterType} in ('fake', 'youtube', 'podcast-rss', 'article-rss', 'readlang-links', 'custom')`),
    check("acquisition_sources_kind_check", sql`${table.sourceKind} in ('video-channel', 'podcast-feed', 'article-feed', 'article-site')`),
    check("acquisition_sources_rights_check", sql`${table.rightsStatus} in ('unknown', 'verified', 'restricted', 'revoked')`),
  ],
);

export const acquisitionRuns = pgTable(
  "acquisition_runs",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    sourceId: uuid("source_id").notNull().references(() => acquisitionSources.id, { onDelete: "restrict" }),
    generationId: text("generation_id").notNull(),
    status: text("status").default("running").notNull(),
    initialCursor: text("initial_cursor"),
    committedCursor: text("committed_cursor"),
    insertedCount: integer("inserted_count").default(0).notNull(),
    duplicateCount: integer("duplicate_count").default(0).notNull(),
    conflictCount: integer("conflict_count").default(0).notNull(),
    estimatedCostMicros: integer("estimated_cost_micros").default(0).notNull(),
    errorCode: text("error_code"),
    startedAt: timestamp("started_at", { withTimezone: true, mode: "date" }).notNull(),
    completedAt: timestamp("completed_at", { withTimezone: true, mode: "date" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex("acquisition_runs_source_generation_uidx").on(table.sourceId, table.generationId),
    index("acquisition_runs_source_started_idx").on(table.sourceId, table.startedAt),
    check("acquisition_runs_status_check", sql`${table.status} in ('running', 'succeeded', 'failed', 'cancelled')`),
    check("acquisition_runs_counts_nonnegative_check", sql`${table.insertedCount} >= 0 and ${table.duplicateCount} >= 0 and ${table.conflictCount} >= 0`),
    check("acquisition_runs_cost_nonnegative_check", sql`${table.estimatedCostMicros} >= 0`),
    check("acquisition_runs_completed_at_check", sql`(${table.status} = 'running' and ${table.completedAt} is null) or (${table.status} <> 'running' and ${table.completedAt} is not null)`),
  ],
);

export const contentCandidates = pgTable(
  "content_candidates",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    sourceId: uuid("source_id").notNull().references(() => acquisitionSources.id, { onDelete: "restrict" }),
    externalItemId: text("external_item_id").notNull(),
    normalizedUrl: text("normalized_url").notNull(),
    title: text("title").notNull(),
    contentType: text("content_type").notNull(),
    language: text("language").notNull(),
    publishedAt: timestamp("published_at", { withTimezone: true, mode: "date" }),
    contentHash: text("content_hash"),
    metadata: jsonb("metadata").$type<JsonObject>().default(sql`'{}'::jsonb`).notNull(),
    status: text("status").default("discovered").notNull(),
    rightsStatus: text("rights_status").default("unknown").notNull(),
    publicationStatus: text("publication_status").default("draft").notNull(),
    publicationRef: jsonb("publication_ref").$type<JsonObject>(),
    publishedCandidateRevision: integer("published_candidate_revision"),
    publishedContentHash: text("published_content_hash"),
    publishedAtInternal: timestamp("published_at_internal", { withTimezone: true, mode: "date" }),
    archivedAt: timestamp("archived_at", { withTimezone: true, mode: "date" }),
    generationId: text("generation_id").notNull(),
    revision: integer("revision").default(1).notNull(),
    lastActivityAt: timestamp("last_activity_at", { withTimezone: true, mode: "date" }).notNull(),
    rejectedAt: timestamp("rejected_at", { withTimezone: true, mode: "date" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex("content_candidates_source_item_uidx").on(table.sourceId, table.externalItemId),
    uniqueIndex("content_candidates_normalized_url_uidx").on(table.normalizedUrl),
    uniqueIndex("content_candidates_content_hash_uidx").on(table.contentHash).where(sql`${table.contentHash} is not null`),
    index("content_candidates_status_activity_idx").on(table.status, table.lastActivityAt),
    check("content_candidates_revision_positive_check", sql`${table.revision} > 0`),
    check("content_candidates_type_check", sql`${table.contentType} in ('video', 'podcast', 'article')`),
    check("content_candidates_status_check", sql`${table.status} in ('discovered', 'screened', 'acquiring', 'processing', 'review_ready', 'failed', 'rejected')`),
    check("content_candidates_rights_check", sql`${table.rightsStatus} in ('unknown', 'verified', 'restricted', 'revoked')`),
    check("content_candidates_publication_check", sql`${table.publicationStatus} in ('draft', 'published', 'archived')`),
    check("content_candidates_hash_check", sql`${table.contentHash} is null or ${table.contentHash} ~ '^[a-f0-9]{64}$'`),
    check("content_candidates_published_hash_check", sql`${table.publishedContentHash} is null or ${table.publishedContentHash} ~ '^[a-f0-9]{64}$'`),
    check("content_candidates_publication_fields_check", sql`(${table.publicationStatus} = 'draft' and ${table.publicationRef} is null and ${table.publishedCandidateRevision} is null and ${table.publishedContentHash} is null and ${table.publishedAtInternal} is null and ${table.archivedAt} is null) or (${table.publicationStatus} = 'published' and ${table.publicationRef} is not null and ${table.publishedCandidateRevision} is not null and ${table.publishedContentHash} is not null and ${table.publishedAtInternal} is not null and ${table.archivedAt} is null) or (${table.publicationStatus} = 'archived' and ${table.publicationRef} is not null and ${table.publishedCandidateRevision} is not null and ${table.publishedContentHash} is not null and ${table.publishedAtInternal} is not null and ${table.archivedAt} is not null)`),
    check("content_candidates_rejected_at_check", sql`(${table.status} = 'rejected' and ${table.rejectedAt} is not null) or (${table.status} <> 'rejected' and ${table.rejectedAt} is null)`),
  ],
);

export const candidateArtifacts = pgTable(
  "candidate_artifacts",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    candidateId: uuid("candidate_id").notNull().references(() => contentCandidates.id, { onDelete: "cascade" }),
    artifactType: text("artifact_type").notNull(),
    storageKey: text("storage_key"),
    contentHash: text("content_hash"),
    byteSize: integer("byte_size").default(0).notNull(),
    status: text("status").default("pending").notNull(),
    ephemeral: boolean("ephemeral").default(false).notNull(),
    retainUntil: timestamp("retain_until", { withTimezone: true, mode: "date" }),
    deletedAt: timestamp("deleted_at", { withTimezone: true, mode: "date" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex("candidate_artifacts_candidate_type_hash_uidx").on(table.candidateId, table.artifactType, table.contentHash),
    index("candidate_artifacts_cleanup_idx").on(table.status, table.retainUntil),
    check("candidate_artifacts_size_nonnegative_check", sql`${table.byteSize} >= 0`),
    check("candidate_artifacts_status_check", sql`${table.status} in ('pending', 'available', 'delete-pending', 'deleted', 'failed')`),
    check("candidate_artifacts_hash_check", sql`${table.contentHash} is null or ${table.contentHash} ~ '^[a-f0-9]{64}$'`),
  ],
);

