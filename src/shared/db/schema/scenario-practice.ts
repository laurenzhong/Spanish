import { sql } from "drizzle-orm";
import {
  boolean,
  check,
  foreignKey,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  real,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";

import { expressions, scenarios } from "./content";
import { createdAt, updatedAt, type JsonObject } from "./common";
import { providerCalls } from "./infrastructure";
import { practiceSessions } from "./training";
import { profiles } from "./users";

export const userSavedExpressions = pgTable(
  "user_saved_expressions",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id").notNull().references(() => profiles.id, { onDelete: "cascade" }),
    expressionId: uuid("expression_id").references(() => expressions.id, { onDelete: "set null" }),
    clientSaveId: text("client_save_id").notNull(),
    sourceText: text("source_text").notNull(),
    translation: text("translation"),
    register: text("register"),
    usageNotes: text("usage_notes"),
    sourceType: text("source_type").notNull(),
    sourceEntityId: text("source_entity_id"),
    sourceVersion: text("source_version"),
    contentHash: text("content_hash"),
    archived: boolean("archived").default(false).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex("user_saved_expressions_user_client_uidx").on(table.userId, table.clientSaveId),
    index("user_saved_expressions_user_created_idx").on(table.userId, table.createdAt),
    check("user_saved_expressions_text_length_check", sql`char_length(${table.sourceText}) between 1 and 1000`),
    check("user_saved_expressions_source_type_check", sql`${table.sourceType} in ('formal-expression', 'reading-selection', 'scenario-review', 'manual')`),
  ],
);

export const personalScenarios = pgTable(
  "personal_scenarios",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id").notNull().references(() => profiles.id, { onDelete: "cascade" }),
    sourceScenarioId: uuid("source_scenario_id").references(() => scenarios.id, { onDelete: "set null" }),
    idempotencyKey: text("idempotency_key").notNull(),
    title: text("title").notNull(),
    cefr: text("cefr").notNull(),
    region: text("region").notNull(),
    skeleton: jsonb("skeleton").$type<JsonObject>().notNull(),
    sourceType: text("source_type").notNull(),
    sourceReference: jsonb("source_reference").$type<JsonObject>().default(sql`'{}'::jsonb`).notNull(),
    sourceVersion: text("source_version"),
    selectedExpressions: jsonb("selected_expressions").$type<string[]>().default(sql`'[]'::jsonb`).notNull(),
    communicationGoals: jsonb("communication_goals").$type<string[]>().default(sql`'[]'::jsonb`).notNull(),
    conditionChanges: jsonb("condition_changes").$type<string[]>().default(sql`'[]'::jsonb`).notNull(),
    providerKey: text("provider_key").notNull(),
    modelVersion: text("model_version").notNull(),
    generationVersion: text("generation_version").notNull(),
    status: text("status").default("ready").notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex("personal_scenarios_user_idempotency_uidx").on(table.userId, table.idempotencyKey),
    uniqueIndex("personal_scenarios_id_user_uidx").on(table.id, table.userId),
    index("personal_scenarios_user_created_idx").on(table.userId, table.createdAt),
    check("personal_scenarios_cefr_check", sql`${table.cefr} in ('A1', 'A2', 'B1', 'B2')`),
    check("personal_scenarios_status_check", sql`${table.status} in ('ready', 'archived')`),
    check("personal_scenarios_source_type_check", sql`${table.sourceType} in ('topic', 'reading', 'saved-expression', 'recent-error')`),
  ],
);

export const scenarioSessionStates = pgTable(
  "scenario_session_states",
  {
    sessionId: uuid("session_id").primaryKey(),
    userId: uuid("user_id").notNull().references(() => profiles.id, { onDelete: "cascade" }),
    personalScenarioId: uuid("personal_scenario_id"),
    clientAttemptId: text("client_attempt_id").notNull(),
    temporaryCharacter: jsonb("temporary_character").$type<JsonObject>().notNull(),
    communicationGoal: text("communication_goal").notNull(),
    triggeredConditions: jsonb("triggered_conditions").$type<string[]>().default(sql`'[]'::jsonb`).notNull(),
    currentTurn: integer("current_turn").default(0).notNull(),
    generationId: text("generation_id"),
    revision: integer("revision").default(1).notNull(),
    stableStatus: text("stable_status").default("awaiting-expression").notNull(),
    hintLevel: integer("hint_level").default(0).notNull(),
    transcriptDraft: text("transcript_draft"),
    transcriptDraftExpiresAt: timestamp("transcript_draft_expires_at", { withTimezone: true, mode: "date" }),
    reviewStatus: text("review_status").default("not-requested").notNull(),
    completionIdempotencyKey: text("completion_idempotency_key"),
    completedAt: timestamp("completed_at", { withTimezone: true, mode: "date" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex("scenario_session_states_user_client_attempt_uidx").on(table.userId, table.clientAttemptId),
    index("scenario_session_states_user_updated_idx").on(table.userId, table.updatedAt),
    foreignKey({ columns: [table.sessionId, table.userId], foreignColumns: [practiceSessions.id, practiceSessions.userId], name: "scenario_session_states_session_user_fk" }).onDelete("cascade"),
    foreignKey({ columns: [table.personalScenarioId, table.userId], foreignColumns: [personalScenarios.id, personalScenarios.userId], name: "scenario_session_states_personal_scenario_user_fk" }).onDelete("restrict"),
    check("scenario_session_states_revision_positive_check", sql`${table.revision} > 0`),
    check("scenario_session_states_turn_nonnegative_check", sql`${table.currentTurn} >= 0`),
    check("scenario_session_states_hint_level_check", sql`${table.hintLevel} between 0 and 3`),
    check("scenario_session_states_stable_status_check", sql`${table.stableStatus} in ('preparing', 'awaiting-expression', 'awaiting-transcript-confirmation', 'paused', 'recoverable-error', 'completed', 'review-pending', 'review-ready')`),
    check("scenario_session_states_review_status_check", sql`${table.reviewStatus} in ('not-requested', 'pending', 'ready', 'unavailable')`),
  ],
);

export const scenarioTurns = pgTable(
  "scenario_turns",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id").notNull().references(() => profiles.id, { onDelete: "cascade" }),
    sessionId: uuid("session_id").notNull(),
    clientAttemptId: text("client_attempt_id").notNull(),
    turnIndex: integer("turn_index").notNull(),
    speaker: text("speaker").notNull(),
    modality: text("modality").notNull(),
    text: text("text").notNull(),
    status: text("status").notNull(),
    attemptId: text("attempt_id"),
    generationId: text("generation_id"),
    replyToTurnId: uuid("reply_to_turn_id"),
    providerCallId: uuid("provider_call_id").references(() => providerCalls.id, { onDelete: "set null" }),
    providerKey: text("provider_key"),
    modelVersion: text("model_version"),
    providerRequestId: text("provider_request_id"),
    completedAt: timestamp("completed_at", { withTimezone: true, mode: "date" }),
    stoppedAt: timestamp("stopped_at", { withTimezone: true, mode: "date" }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex("scenario_turns_user_client_attempt_uidx").on(table.userId, table.clientAttemptId),
    uniqueIndex("scenario_turns_session_position_uidx").on(table.sessionId, table.turnIndex),
    uniqueIndex("scenario_turns_id_user_uidx").on(table.id, table.userId),
    index("scenario_turns_user_session_idx").on(table.userId, table.sessionId),
    foreignKey({ columns: [table.sessionId, table.userId], foreignColumns: [practiceSessions.id, practiceSessions.userId], name: "scenario_turns_session_user_fk" }).onDelete("cascade"),
    foreignKey({ columns: [table.replyToTurnId, table.userId], foreignColumns: [table.id, table.userId], name: "scenario_turns_reply_to_user_fk" }).onDelete("cascade"),
    check("scenario_turns_position_nonnegative_check", sql`${table.turnIndex} >= 0`),
    check("scenario_turns_speaker_check", sql`${table.speaker} in ('user', 'temporary-character', 'condition')`),
    check("scenario_turns_modality_check", sql`${table.modality} in ('speech', 'typing', 'system')`),
    check("scenario_turns_status_check", sql`${table.status} in ('pending', 'completed', 'stopped', 'failed')`),
    check("scenario_turns_text_length_check", sql`char_length(${table.text}) between 1 and 4000`),
    check("scenario_turns_completed_at_check", sql`(${table.status} = 'completed' and ${table.completedAt} is not null) or (${table.status} <> 'completed' and ${table.completedAt} is null)`),
  ],
);

